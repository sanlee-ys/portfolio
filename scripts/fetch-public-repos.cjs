#!/usr/bin/env node
/*
 * Fetch the public GitHub fields for the repositories this site already names,
 * and write src/data/public-repos.json.
 *
 * WHY A SNAPSHOT. The site is a static build. A browser fetch would add JS and
 * would fail on a laptop with no network. This script runs at build time. If
 * the network fails, the last committed snapshot stays, and the build continues.
 *
 * WHY AN ALLOWLIST. ADR-003 forbids a survey of "all my repos". The GitHub
 * public list also contains forks and profile noise this site does not name.
 * The allowlist is the repos already linked from published pages, checked
 * against `gh repo list sanlee-ys --visibility public` on 2026-09-09. Do not
 * add a name that is not already a link on a published page.
 *
 * WHY THIS ENDPOINT. GET /users/{user}/repos returns public repos only, even
 * with a token. GET /user/repos can see private repos. This script never calls
 * that. A token, if present, only raises the rate limit.
 *
 * Live fields: description, primary language, last-push date, repo URL.
 * Stars are vanity and are not written.
 *
 * Run from the repo root:
 *     node scripts/fetch-public-repos.cjs
 */
const fs = require('fs');
const path = require('path');

const OWNER = 'sanlee-ys';
const REPO_ROOT = path.resolve(__dirname, '..');
const OUT_PATH = path.join(REPO_ROOT, 'src', 'data', 'public-repos.json');

/*
 * Repos already linked as github.com/sanlee-ys/<name> from site source at
 * 2cf5ce5. Each name was on the public list on 2026-09-09. winget-pkgs (a
 * fork) and sanlee-ys (the profile repo) are public and are not linked, so
 * they stay out.
 */
const ALLOWLIST = new Set([
  'agent-ops',
  'architecture',
  'defense-news-classifier',
  'faithfulness-judge',
  'kb-agent',
  'learning-notes',
  'netops-lab',
  'notes-api',
  'portfolio',
  'telltale',
]);

const ROW_KEYS = ['name', 'description', 'language', 'pushedAt', 'url'];

function isoDate(value) {
  if (typeof value !== 'string') return null;
  const m = value.match(/^(\d{4}-\d{2}-\d{2})/);
  return m ? m[1] : null;
}

function cleanText(value) {
  if (typeof value !== 'string') return null;
  const text = value.trim();
  return text ? text : null;
}

function selectFields(repo) {
  const name = typeof repo.name === 'string' ? repo.name.trim() : '';
  return {
    name,
    description: cleanText(repo.description),
    language: cleanText(repo.language),
    pushedAt: isoDate(repo.pushed_at),
    url: `https://github.com/${OWNER}/${name}`,
  };
}

function toSnapshot(apiRepos, { fetchedAt, allowlist = ALLOWLIST } = {}) {
  const repos = [];
  for (const raw of apiRepos) {
    if (!raw || raw.private) continue;
    if (typeof raw.name !== 'string' || !allowlist.has(raw.name)) continue;
    const row = selectFields(raw);
    if (!row.name) continue;
    repos.push(row);
  }
  repos.sort((a, b) => {
    if (a.pushedAt && b.pushedAt && a.pushedAt !== b.pushedAt) {
      return a.pushedAt < b.pushedAt ? 1 : -1;
    }
    if (a.pushedAt && !b.pushedAt) return -1;
    if (!a.pushedAt && b.pushedAt) return 1;
    return a.name < b.name ? -1 : 1;
  });
  return {
    note:
      'Generated by scripts/fetch-public-repos.cjs. Allowlisted public repos only. Do not add names by hand.',
    generatedBy: 'scripts/fetch-public-repos.cjs',
    fetchedAt: fetchedAt || null,
    repos,
  };
}

function resolveSnapshot(previous, result) {
  if (!result.ok) {
    return { snapshot: previous, kept: true, error: result.error };
  }
  return {
    snapshot: toSnapshot(result.apiRepos, { fetchedAt: result.fetchedAt }),
    kept: false,
  };
}

function readSnapshot(filePath) {
  if (!fs.existsSync(filePath)) return { fetchedAt: null, repos: [] };
  try {
    const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
    if (!data || !Array.isArray(data.repos)) return { fetchedAt: null, repos: [] };
    return data;
  } catch {
    return { fetchedAt: null, repos: [] };
  }
}

function writeSnapshot(snapshot, filePath) {
  const body = `${JSON.stringify(snapshot, null, 2)}\n`;
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, body);
}

async function fetchPublicRepos() {
  const headers = {
    'User-Agent': 'sanlee-portfolio-fetch-public-repos',
    Accept: 'application/vnd.github+json',
  };
  // Token raises the rate limit only. The endpoint is public-only.
  if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  const repos = [];
  for (let page = 1; page <= 10; page += 1) {
    const url = `https://api.github.com/users/${OWNER}/repos?per_page=100&page=${page}&type=public`;
    const res = await fetch(url, { headers });
    if (!res.ok) throw new Error(`GitHub API ${res.status} fetching public repos (page ${page})`);
    const batch = await res.json();
    if (!Array.isArray(batch) || batch.length === 0) break;
    repos.push(...batch);
    if (batch.length < 100) break;
  }
  return repos;
}

function todayUtc() {
  return new Date().toISOString().slice(0, 10);
}

async function main() {
  const previous = readSnapshot(OUT_PATH);
  let result;
  try {
    const apiRepos = await fetchPublicRepos();
    result = { ok: true, apiRepos, fetchedAt: todayUtc() };
  } catch (err) {
    result = { ok: false, error: err };
  }

  const { snapshot, kept, error } = resolveSnapshot(previous, result);
  if (kept) {
    if (previous.repos && previous.repos.length) {
      console.warn(
        `fetch-public-repos: ${error.message}; keeping last snapshot (${previous.repos.length} repo(s)).`
      );
      process.exit(0);
    }
    console.error(`✗ fetch-public-repos: ${error.message} and no snapshot to keep.`);
    process.exit(1);
  }

  writeSnapshot(snapshot, OUT_PATH);
  console.log(
    `OK - wrote ${snapshot.repos.length} public repo(s) to src/data/public-repos.json`
  );
}

if (require.main === module) {
  main().catch((err) => {
    console.error(`✗ fetch-public-repos: ${err.message}`);
    process.exit(1);
  });
}

module.exports = {
  OWNER,
  ALLOWLIST,
  ROW_KEYS,
  isoDate,
  selectFields,
  toSnapshot,
  resolveSnapshot,
  readSnapshot,
  writeSnapshot,
};
